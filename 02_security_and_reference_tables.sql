/* ================================================================
   TMS SECURITY AND REFERENCE TABLES
   Blueprint Version : v1.5

   IMPORTANT BUSINESS RULES
   ----------------------------------------------------------------
   1. Super User Organization is a dedicated platform organization.
   2. Users associated with the Super User Organization may have
      multiple organization memberships.
   3. Normal customer-organization users may belong to only one
      organization.
   4. Organization membership and role assignment remain separate.
   5. Super User authority is NOT represented by a permission.
   6. TMS_ROLE_DETAILS.IS_SYSTEM_ROLE identifies system roles.
   7. Data integrity and business rules remain applicable to
      Super User.
   ================================================================ */


/* ================================================================
   1. ROLES
   ================================================================ */

CREATE TABLE tms_roles (
  role_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id NUMBER,
  role_code VARCHAR2(100) NOT NULL,
  role_name VARCHAR2(200) NOT NULL,
  status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL
      CHECK (status IN ('ACTIVE','INACTIVE')),
  created_by VARCHAR2(255) NOT NULL,
  created_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_by VARCHAR2(255),
  updated_date TIMESTAMP,
