/* ================================================================
   20. DELEGATION SCOPE VALIDATION
   ----------------------------------------------------------------
   Delegation must remain inside the organization.

   Both delegator and delegate must have an active membership in
   the delegated organization.
   ================================================================ */

CREATE OR REPLACE TRIGGER trg_tms_delegation_scope
BEFORE INSERT OR UPDATE OF
    delegator_user_id,
    delegate_user_id,
    org_id
ON tms_delegations
FOR EACH ROW
DECLARE

    L_COUNT NUMBER;

BEGIN

    /* ------------------------------------------------------------
       Delegator membership
       ------------------------------------------------------------ */

    SELECT COUNT(*)
      INTO L_COUNT
      FROM TMS_USER_ORGANIZATIONS UO
     WHERE UO.USER_ID = :NEW.DELEGATOR_USER_ID
       AND UO.ORG_ID = :NEW.ORG_ID
       AND UO.MEMBERSHIP_STATUS = 'ACTIVE';


    IF L_COUNT = 0 THEN

        RAISE_APPLICATION_ERROR(
            -20024,
            'TMS-SECURITY-024: Delegator is not an active member '
            || 'of the delegated organization.'
        );

    END IF;


    /* ------------------------------------------------------------
       Delegate membership
       ------------------------------------------------------------ */

    SELECT COUNT(*)
      INTO L_COUNT
      FROM TMS_USER_ORGANIZATIONS UO
     WHERE UO.USER_ID = :NEW.DELEGATE_USER_ID
       AND UO.ORG_ID = :NEW.ORG_ID
       AND UO.MEMBERSHIP_STATUS = 'ACTIVE';


    IF L_COUNT = 0 THEN

        RAISE_APPLICATION_ERROR(
            -20025,
            'TMS-SECURITY-025: Delegate is not an active member '
            || 'of the delegated organization.'
        );

    END IF;


    /* ------------------------------------------------------------
       Delegation role must be global or belong to the same
       organization.
       ------------------------------------------------------------ */

    IF :NEW.ROLE_ID IS NOT NULL THEN

        SELECT COUNT(*)
          INTO L_COUNT
          FROM TMS_ROLES R
         WHERE R.ROLE_ID = :NEW.ROLE_ID
           AND (
                  R.ORG_ID IS NULL
                  OR R.ORG_ID = :NEW.ORG_ID
               );


        IF L_COUNT = 0 THEN

            RAISE_APPLICATION_ERROR(
                -20026,
                'TMS-SECURITY-026: Delegated role is outside '
                || 'the organization scope.'
            );

        END IF;

    END IF;

END trg_tms_delegation_scope;
/


