    ON tms_user_organizations (
        user_id,
        org_id
    );


/* ================================================================
   14. ONE PRIMARY ORGANIZATION PER USER
   ----------------------------------------------------------------
   Oracle NULL behavior allows the following design:

       is_primary = 'Y'
           -> only one row per user

       is_primary = 'N'
           -> unlimited rows

   This supports multiple memberships while preserving exactly
   one primary membership.
   ================================================================ */

CREATE UNIQUE INDEX uq_tms_user_primary_org
    ON tms_user_organizations (
        CASE
            WHEN is_primary = 'Y'
            THEN user_id
        END
    );


