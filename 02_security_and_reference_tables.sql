/* ================================================================
   16. ORGANIZATION MEMBERSHIP CONTROL
   ----------------------------------------------------------------
   BUSINESS RULE:

   A user may have multiple organization memberships ONLY when
   the user is associated with the dedicated Super User
   Organization.

   The Super User Organization is identified by:

       ORG_TYPE = 'SUPER_USER'

   This avoids depending on an identity-generated ORG_ID.

   Examples:

       Normal customer user
           Org A -> allowed
           Org B -> rejected

       Super User Organization user
           Super User Org -> allowed
           Customer A     -> allowed
           Customer B     -> allowed
           Customer C     -> allowed
   ================================================================ */

CREATE OR REPLACE TRIGGER trg_tms_user_org_membership
FOR INSERT OR UPDATE OF user_id, org_id, membership_status
ON tms_user_organizations
COMPOUND TRIGGER

    TYPE t_user_id_list IS TABLE OF NUMBER
        INDEX BY VARCHAR2(100);

    G_USER_IDS t_user_id_list;


    AFTER EACH ROW IS
    BEGIN

        G_USER_IDS(TO_CHAR(:NEW.user_id)) := :NEW.user_id;

    END AFTER EACH ROW;


    AFTER STATEMENT IS

        L_USER_ID               NUMBER;
        L_ORG_COUNT             NUMBER;
        L_SUPER_USER_ORG_COUNT  NUMBER;

    BEGIN

        L_USER_ID := G_USER_IDS.FIRST;

        WHILE L_USER_ID IS NOT NULL LOOP

            /* --------------------------------------------------------
               Count active/suspended organizations for this user.

               INACTIVE memberships do not count as current
               organization memberships.
               -------------------------------------------------------- */

            SELECT COUNT(DISTINCT UO.ORG_ID)
              INTO L_ORG_COUNT
              FROM TMS_USER_ORGANIZATIONS UO
             WHERE UO.USER_ID = G_USER_IDS(L_USER_ID)
               AND UO.MEMBERSHIP_STATUS IN ('ACTIVE','SUSPENDED');


            /* --------------------------------------------------------
               Determine whether this user is linked with the
               dedicated Super User Organization.

               ORG_TYPE is used rather than ORG_ID.
               -------------------------------------------------------- */

            SELECT COUNT(*)
              INTO L_SUPER_USER_ORG_COUNT
              FROM TMS_USER_ORGANIZATIONS UO
                   JOIN TMS_ORGANIZATIONS O
                     ON O.ORG_ID = UO.ORG_ID
             WHERE UO.USER_ID = G_USER_IDS(L_USER_ID)
               AND UO.MEMBERSHIP_STATUS IN ('ACTIVE','SUSPENDED')
               AND O.ORG_TYPE = 'SUPER_USER';


            /* --------------------------------------------------------
               Normal customer user:

               Maximum one organization.
               -------------------------------------------------------- */

            IF L_SUPER_USER_ORG_COUNT = 0
               AND L_ORG_COUNT > 1
            THEN

                RAISE_APPLICATION_ERROR(
                    -20021,
                    'TMS-SECURITY-021: A customer organization user '
                    || 'may belong to only one organization.'
                );

            END IF;


            L_USER_ID := G_USER_IDS.NEXT(L_USER_ID);

        END LOOP;

    END AFTER STATEMENT;

END trg_tms_user_org_membership;
/


/* ================================================================
   17. ORGANIZATION / DEPARTMENT CONSISTENCY
   ----------------------------------------------------------------
   A membership department must belong to the same organization
   as the membership.
   ================================================================ */

CREATE OR REPLACE TRIGGER trg_tms_user_org_department
BEFORE INSERT OR UPDATE OF org_id, department_id
ON tms_user_organizations
FOR EACH ROW
DECLARE

    L_COUNT NUMBER;

BEGIN

    IF :NEW.department_id IS NULL THEN
        RETURN;
    END IF;


    SELECT COUNT(*)
      INTO L_COUNT
      FROM TMS_DEPARTMENTS D
     WHERE D.DEPARTMENT_ID = :NEW.DEPARTMENT_ID
       AND D.ORG_ID = :NEW.ORG_ID;


    IF L_COUNT = 0 THEN

        RAISE_APPLICATION_ERROR(
            -20022,
            'TMS-SECURITY-022: Department does not belong '
            || 'to the selected organization.'
        );

    END IF;

END trg_tms_user_org_department;
/


/* ================================================================
   18. ROLE / ORGANIZATION CONSISTENCY
   ----------------------------------------------------------------
   A role attached to a membership must either be:

       1. Global      -> TMS_ROLES.ORG_ID IS NULL

   OR

       2. Same organization as the membership.

   This prevents a role belonging to Organization A from being
   assigned to a user membership belonging to Organization B.
   ================================================================ */

CREATE OR REPLACE TRIGGER trg_tms_user_org_role_scope
BEFORE INSERT OR UPDATE OF user_org_id, role_id
ON tms_user_organization_roles
FOR EACH ROW
DECLARE

    L_MEMBERSHIP_ORG_ID NUMBER;
    L_ROLE_ORG_ID       NUMBER;

BEGIN

    SELECT ORG_ID
      INTO L_MEMBERSHIP_ORG_ID
      FROM TMS_USER_ORGANIZATIONS
     WHERE USER_ORG_ID = :NEW.USER_ORG_ID;


    SELECT ORG_ID
      INTO L_ROLE_ORG_ID
      FROM TMS_ROLES
     WHERE ROLE_ID = :NEW.ROLE_ID;


    IF L_ROLE_ORG_ID IS NOT NULL
       AND L_ROLE_ORG_ID <> L_MEMBERSHIP_ORG_ID
    THEN

        RAISE_APPLICATION_ERROR(
            -20023,
            'TMS-SECURITY-023: Organization-specific role '
            || 'cannot be assigned outside its organization.'
        );

    END IF;

END trg_tms_user_org_role_scope;
/


