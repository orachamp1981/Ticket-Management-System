CREATE TABLE TMS_APPLICATIONS (
    APPLICATION_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    APPLICATION_CODE VARCHAR2(50)  NOT NULL,
    APPLICATION_NAME VARCHAR2(200) NOT NULL,
    DESCRIPTION      VARCHAR2(1000),
    STATUS            VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_BY       NUMBER,
    CREATED_DATE     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY       NUMBER,
    UPDATED_DATE     TIMESTAMP,
    RECORD_VERSION   NUMBER DEFAULT 1 NOT NULL,

    CONSTRAINT PK_TMS_APPLICATIONS
        PRIMARY KEY (APPLICATION_ID),

    CONSTRAINT UK_TMS_APPLICATION_CODE
        UNIQUE (APPLICATION_CODE),

    CONSTRAINT CK_TMS_APPLICATION_STATUS
        CHECK (STATUS IN ('ACTIVE','INACTIVE'))
);
/

CREATE TABLE TMS_ORGANIZATION_APPLICATIONS (
    ORG_APPLICATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ORG_ID             NUMBER NOT NULL,
    APPLICATION_ID     NUMBER NOT NULL,
    STATUS             VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    EFFECTIVE_FROM    DATE DEFAULT SYSDATE NOT NULL,
    EFFECTIVE_TO      DATE,
    CREATED_BY        NUMBER,
    CREATED_DATE      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY        NUMBER,
    UPDATED_DATE      TIMESTAMP,
    RECORD_VERSION    NUMBER DEFAULT 1 NOT NULL,

    CONSTRAINT PK_TMS_ORG_APPLICATIONS
        PRIMARY KEY (ORG_APPLICATION_ID),

    CONSTRAINT UK_TMS_ORG_APPLICATION
        UNIQUE (ORG_ID, APPLICATION_ID),

    CONSTRAINT FK_TMS_OA_ORG
        FOREIGN KEY (ORG_ID)
        REFERENCES TMS_ORGANIZATIONS (ORG_ID),

    CONSTRAINT FK_TMS_OA_APPLICATION
        FOREIGN KEY (APPLICATION_ID)
        REFERENCES TMS_APPLICATIONS (APPLICATION_ID),

    CONSTRAINT CK_TMS_OA_STATUS
        CHECK (STATUS IN ('ACTIVE','INACTIVE')),

    CONSTRAINT CK_TMS_OA_DATES
        CHECK (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO >= EFFECTIVE_FROM)
);
/

